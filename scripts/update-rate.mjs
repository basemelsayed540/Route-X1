// Fetches today's USD -> EGP rate and writes it to src/data/exchangeRate.ts.
// Runs in the daily GitHub Actions deploy (see .github/workflows/deploy.yml), and by hand with:
//   npm run update-rate
//
// Safe by design: if every source fails, or returns a value that is not plausible, the existing
// file is left untouched and the script still exits 0 so the site keeps deploying with the last
// known rate.

import { readFileSync, writeFileSync } from "node:fs";

const OUT = new URL("../src/data/exchangeRate.ts", import.meta.url);

// Free sources that need no API key, tried in order. RATE_API_URL is for testing.
const SOURCES = [
  process.env.RATE_API_URL,
  "https://open.er-api.com/v6/latest/USD",
  "https://cdn.jsdelivr.net/npm/@fawazahmed0/currency-api@latest/v1/currencies/usd.json",
  "https://latest.currency-api.pages.dev/v1/currencies/usd.json"
].filter(Boolean);

const MIN_RATE = 10;
const MAX_RATE = 500;

function extractRate(json) {
  // open.er-api.com -> { rates: { EGP } }   fawazahmed0 -> { usd: { egp } }
  const v = json?.rates?.EGP ?? json?.usd?.egp;
  return typeof v === "number" ? v : Number.NaN;
}

async function fetchRate() {
  for (const url of SOURCES) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(10_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const rate = extractRate(await res.json());
      if (!Number.isFinite(rate) || rate < MIN_RATE || rate > MAX_RATE) {
        throw new Error(`implausible rate: ${rate}`);
      }
      return { rate, url };
    } catch (err) {
      console.warn(`rate source failed (${url}): ${err.message}`);
    }
  }
  return null;
}

const found = await fetchRate();
if (!found) {
  console.warn("No source returned a usable rate. Keeping the existing rate.");
  process.exit(0);
}

const rate = Math.round(found.rate * 100) / 100;
const today = new Date().toISOString().slice(0, 10);

const next = `// AUTO-GENERATED by scripts/update-rate.mjs (runs daily in the deploy workflow). Do not edit by hand.
// Source: ${new URL(found.url).host}
export const EGP_PER_USD = ${rate};
export const RATE_UPDATED = "${today}";
`;

let current = "";
try {
  current = readFileSync(OUT, "utf8");
} catch {
  /* first run */
}
if (current !== next) writeFileSync(OUT, next);
console.log(`1 USD = ${rate} EGP (${found.url}) -> ${current === next ? "unchanged" : "updated"}`);
